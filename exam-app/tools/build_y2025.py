FIX = {"仸": "任", "务势": "劣势", "培兹": "培养", "（）": "（ ）"}


def clean(s):
    for a, b in FIX.items():
        s = s.replace(a, b)
    return s.strip()


def parse():
    text = SRC.read_text(encoding="utf-8")
    secs = re.split(r"\n\s*(判断题|单选题|多选题|简答题)（\d+\s*题）", text)
    # secs: [head, name, body, name, body ...]
    out = {}
    for i in range(1, len(secs), 2):
        name, body = secs[i], secs[i + 1]
        items, cur = [], None
        for raw in body.splitlines():
            line = re.sub(r"[\ue000-\uf8ff]", "", raw).strip()
            if not line:
                continue
            m = re.match(r"^(\d+)\.\s*(.*)$", line)
            o = re.match(r"^([A-D])\s*[\.．]\s*(.*)$", line)
            if m and not o:
                cur = {"no": int(m.group(1)), "stem": m.group(2), "options": []}
                items.append(cur)
            elif o and cur is not None:
                cur["options"].append(o.group(2))
            elif cur is not None:
                if cur["options"]:
                    cur["options"][-1] += line
                else:
                    cur["stem"] += line
        out[name] = items
    return out


