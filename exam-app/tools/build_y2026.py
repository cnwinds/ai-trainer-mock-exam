def guide_md(g):
    pts = g["points"]
    out = ["**考场速写版**（每点一行，直接誊抄）：", ""]
    out += [f"{i}. {p['t']}：{p['quick']}" for i, p in enumerate(pts, 1)]
    out += ["", f"> 记忆钩子：{g['hook']}", "", "**理解版**：", ""]
    for i, p in enumerate(pts, 1):
        out += [f"**{i}. {p['t']}**", "", f"**怎么做**：{p['how']}", "", f"**为什么**：{p['why']}", ""]
        if p.get("tip"):
            out += [f"**小提醒**：{p['tip']}", ""]
    out += ["**本题术语**：", ""] + [f"- **{t}**：{d}" for t, d in g["terms"]]
    return "\n".join(out).strip()


def guide_json(g):
    return {"hook": g["hook"], "points": g["points"], "terms": [{"t": t, "d": d} for t, d in g["terms"]]}


