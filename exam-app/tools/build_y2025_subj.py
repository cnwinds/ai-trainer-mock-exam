def short_stems():
    t = (TXT / "理论知识试题.txt").read_text(encoding="utf-8").replace("仸", "任")
    body = re.split(r"简答题（6\s*题）", t)[1]
    body = re.sub(r"[\ue000-\uf8ff]", "", body)
    parts = re.split(r"\n\s*(\d)\.\s*", "\n" + body)
    stems = {}
    for i in range(1, len(parts), 2):
        stems[int(parts[i])] = re.sub(r"\s*\n\s*", "", parts[i + 1]).replace("a）", "\na）").replace("b）", "\nb）").replace("c）", "\nc）").replace("请您", "\n请您").strip()
    return stems


