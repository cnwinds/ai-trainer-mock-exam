def case_stem(fn):
    lines = (TXT / fn).read_text(encoding="utf-8").splitlines()
    keep = []
    for ln in lines:
        s = re.sub(r"[\ue000-\uf8ff]", "•", ln).replace("仸", "任").rstrip()
        if re.search(r"第\s*\d+\s*页|^\s*人工智能训练师(技能操作|综合评审)考核试题单\s*$|^\s*第\d页", s):
            continue
        keep.append(s)
    txt = "\n".join(keep)
    txt = re.sub(r"\n{3,}", "\n\n", txt).strip()
    return txt


